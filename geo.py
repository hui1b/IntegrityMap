# 精确点位坐标 (覆盖学校主坐标)
EXACT_POINT_COORDS = {
    "钱学森图书馆": (121.4360, 31.2010), # 上海交通大学徐汇校区
}

def fill_coordinates(data):
    """为点位填充经纬度"""
    points = data.get("points", [])
    filled_count = 0
    null_count = 0

    for point in points:
        school = point.get("schoolName", "").strip()
        title = point.get("title", "")
        
        lng, lat = None, None
        
        # 1. 优先匹配精确点位
        for exact_name, coords in EXACT_POINT_COORDS.items():
            if exact_name in title:
                lng, lat = coords
                break
        
        # 2. 匹配学校坐标
        if lng is None and school in SCHOOL_COORDS:
            lng, lat = SCHOOL_COORDS[school]
        
        # 3. 填充结果
        if lng is not None:
            point["lng"] = round(lng, 6)
            point["lat"] = round(lat, 6)
            filled_count += 1
        else:
            point["lng"] = None
            point["lat"] = None
            null_count += 1
            print(f"⚠️ 未找到坐标: {school} - {title}")
            
    print(f"\n处理完成: {filled_count} 个点位已填充, {null_count} 个点位待补充。")
    return data

if __name__ == "__main__":
    with open("data.json", "r", encoding="utf-8") as f:
        data = json.load(f)
    
    data = fill_coordinates(data)
    
    with open("data_with_coords.json", "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    
